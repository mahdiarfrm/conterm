import Foundation

/// Installs / removes a Pi-family extension that drives Conterm's
/// per-pane status pill, mirroring the opencode integration.
///
/// Pi and its fork OMP both auto-discover TypeScript extensions in
/// `~/.pi/agent/extensions/` and `~/.omp/agent/extensions/`
/// respectively, with the same ExtensionAPI (`pi.on(...)`). One
/// template serves both; only the identity in the OSC differs:
/// `OSC 9 ; conterm-agent:<pi|omp>:<state> BEL` to the tty, or —
/// when Conterm's ssh wrapper provided one — a JSON line to the
/// forwarded unix socket in `$CONTERM_AGENT_SOCK` (see
/// `RemoteAgentChannel`).
///
/// Events used:
///   session_start        → start  → "<Agent> is Ready."
///   turn_start           → prompt → "<Agent> is thinking…"
///   tool_execution_start → tool:start (bubble for the call)
///   tool_execution_end   → tool:end:ok|fail
///   agent_end            → idle   → back to Ready
///   session_shutdown / process exit → end → pill disappears
///
/// Install = write our own file, uninstall = delete it; the user's
/// config and other extensions are never touched.
@MainActor
enum ExtensionIntegration {
    static func plugin(identity: String) -> String {
        #"""
        // Auto-generated by Conterm — drives Conterm's agent status pill.
        // Safe to delete (or toggle off the integration in Conterm).
        import { writeFileSync } from "node:fs";
        import { connect } from "node:net";

        const AGENT = "__IDENTITY__";
        let last = "";
        function osc(state) {
          return "\x1b]9;conterm-agent:" + AGENT + ":" + state + "\x07";
        }
        function send(state) {
          if (state === last) return;
          last = state;
          const sock = process.env.CONTERM_AGENT_SOCK;
          if (sock) {
            try {
              const c = connect(sock);
              c.on("error", () => {
                try { writeFileSync("/dev/tty", osc(state)); } catch (e) {}
              });
              c.write(JSON.stringify({
                agent: AGENT,
                pane: process.env.CONTERM_PANE_ID || "",
                state: state,
              }) + "\n");
              c.end();
              return;
            } catch (e) { /* fall through to the tty */ }
          }
          try { writeFileSync("/dev/tty", osc(state)); } catch (e) {}
        }

        let ended = false;
        function end() { if (!ended) { ended = true; last = ""; send("end"); } }
        process.on("exit", end);

        export default function (pi) {
          send("start");
          pi.on("session_start", async () => send("start"));
          pi.on("turn_start", async () => send("prompt"));
          pi.on("tool_execution_start", async (event) => {
            const id = event && event.toolCallId;
            if (!id) { send("prompt"); return; }
            let excerpt = "";
            try {
              excerpt = Buffer.from(
                JSON.stringify(event.args || {}).slice(0, 200)
              ).toString("base64");
            } catch (e) {}
            last = "";
            send("tool:start:" + id + ":" +
                 ((event && event.toolName) || "tool") + ":" + excerpt);
          });
          pi.on("tool_execution_end", async (event) => {
            const id = event && event.toolCallId;
            if (!id) return;
            last = "";
            send("tool:end:" + id + ":" +
                 (event && event.isError ? "fail" : "ok"));
          });
          pi.on("agent_end", async () => send("idle"));
          pi.on("session_shutdown", async () => end());
        }
        """#.replacingOccurrences(of: "__IDENTITY__", with: identity)
    }

    static func isInstalled(at path: String) -> Bool {
        FileManager.default.fileExists(atPath: path)
    }

    static func install(identity: String, at path: String) {
        let dir = (path as NSString).deletingLastPathComponent
        try? FileManager.default.createDirectory(
            atPath: dir, withIntermediateDirectories: true)
        try? plugin(identity: identity).write(
            toFile: path, atomically: true, encoding: .utf8)
    }

    static func uninstall(at path: String) {
        try? FileManager.default.removeItem(atPath: path)
    }

    static func refresh(identity: String, at path: String) {
        if isInstalled(at: path) { install(identity: identity, at: path) }
    }
}

/// Pi's extension in `~/.pi/agent/extensions/`.
@MainActor
enum PiIntegration {
    static let identity = "pi"
    static var path: String {
        "\(InstanceState.userHome)/.pi/agent/extensions/conterm-agent.ts"
    }
    static var isInstalled: Bool { ExtensionIntegration.isInstalled(at: path) }
    static func install() { ExtensionIntegration.install(identity: identity, at: path) }
    static func uninstall() { ExtensionIntegration.uninstall(at: path) }
    static func refreshIfInstalled() {
        ExtensionIntegration.refresh(identity: identity, at: path)
    }
}

